#!/usr/bin/env python3
"""
05_generate_report.py

Creates an AWS Audit Manager Assessment Report for a given assessment_id.
Optionally waits/polls until the report is completed and then prints key details.

Notes:
- The report file is delivered to the S3 destination configured on the assessment
  (assessmentReportsDestination). If that destination is not configured, create_assessment_report
  may fail or produce incomplete outcomes depending on your environment.
- This script does NOT download the report; it only creates it and (optionally) polls status.
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime, timezone

import boto3


def utc_ts() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def jprint(obj):
    print(json.dumps(obj, indent=2, ensure_ascii=False, default=str))


def get_assessment(audit, assessment_id: str) -> dict:
    return audit.get_assessment(assessmentId=assessment_id)["assessment"]


def ensure_destination_configured(assessment: dict) -> dict:
    # Best-effort check. Some accounts may have empty destinationType or missing destination config.
    dest = assessment.get("assessmentReportsDestination", {})
    return dest


def create_report(audit, assessment_id: str, name: str, description: str | None = None) -> dict:
    kwargs = {
        "assessmentId": assessment_id,
        "name": name,
    }
    if description:
        kwargs["description"] = description

    resp = audit.create_assessment_report(**kwargs)
    # Response includes "assessmentReport" with id/arn/name/status, etc.
    return resp["assessmentReport"]


def get_report(audit, assessment_id: str, report_id: str) -> dict:
    # Audit Manager supports get_assessment_report
    resp = audit.get_assessment_report(assessmentId=assessment_id, assessmentReportId=report_id)
    return resp["assessmentReport"]


def poll_report(audit, assessment_id: str, report_id: str, interval: int, timeout: int) -> dict:
    start = time.time()
    last = None
    while True:
        rep = get_report(audit, assessment_id, report_id)
        status = rep.get("status")
        last = rep
        if status in ("COMPLETE", "FAILED"):
            return rep

        if time.time() - start > timeout:
            return rep

        time.sleep(interval)


def main():
    ap = argparse.ArgumentParser(description="Generate an AWS Audit Manager assessment report (ISO22301 evidence pack).")
    ap.add_argument("--region", default=os.getenv("AWS_REGION", "us-east-1"))
    ap.add_argument("--assessment-id", required=True)
    ap.add_argument("--name", default=None, help="Report name. Default: ISO22301-Report-<timestamp>")
    ap.add_argument("--description", default="ISO 22301 emulation assessment report generated by automation.")
    ap.add_argument("--wait", action="store_true", help="Poll until COMPLETE/FAILED or timeout.")
    ap.add_argument("--poll-interval", type=int, default=15, help="Seconds between status checks when --wait is used.")
    ap.add_argument("--timeout", type=int, default=900, help="Max seconds to wait when --wait is used.")
    ap.add_argument("--print-assessment-destination", action="store_true", help="Print assessment report destination config.")
    args = ap.parse_args()

    audit = boto3.client("auditmanager", region_name=args.region)

    # Fetch assessment and show destination (useful troubleshooting)
    assessment = get_assessment(audit, args.assessment_id)
    dest = ensure_destination_configured(assessment)

    if args.print_assessment_destination:
        print("[INFO] AssessmentReportsDestination:")
        jprint(dest)

    # Name default
    report_name = args.name or f"ISO22301-Report-{utc_ts()}"

    # Create report
    try:
        report = create_report(audit, args.assessment_id, report_name, args.description)
    except Exception as e:
        print("[ERROR] Failed to create assessment report.")
        print(str(e))
        # Helpful hint if destination looks empty
        if not dest or not dest.get("destinationType"):
            print(
                "\n[HINT] Your assessmentReportsDestination might be missing or not fully configured.\n"
                "       Ensure the assessment has an S3 destination configured for reports.\n"
            )
        sys.exit(1)

    print("[OK] Report creation requested:")
    jprint({
        "assessment_id": args.assessment_id,
        "report_id": report.get("id"),
        "report_arn": report.get("arn"),
        "name": report.get("name"),
        "status": report.get("status"),
        "region": args.region
    })

    if args.wait:
        final_rep = poll_report(audit, args.assessment_id, report["id"], args.poll_interval, args.timeout)
        print("\n[INFO] Final report status:")
        jprint({
            "report_id": final_rep.get("id"),
            "status": final_rep.get("status"),
            "created_at": final_rep.get("creationTime"),
            "updated_at": final_rep.get("lastUpdated"),
            "s3_destination": dest
        })

        if final_rep.get("status") == "FAILED":
            print("\n[ERROR] Report generation FAILED. Check Audit Manager console for details and IAM permissions.")
        elif final_rep.get("status") != "COMPLETE":
            print("\n[WARN] Timed out waiting. Re-run with higher --timeout or check console.")
        else:
            # Often the console will show the report location; API doesn't always surface the final object key.
            print("\n[OK] Report generation COMPLETE. Retrieve it from the configured S3 destination (Audit Manager reports).")


if __name__ == "__main__":
    main()
